# Builds whole_code/2026_plain_email_all_blocks.html: the empty template with every block pasted into its slot.
# Block order comes from blocks.order.txt; a new block file is picked up automatically (added at the end), add its
# name there only to put it in the right place. Blocks in blocks/footer/ go into the footer slot, the rest into content.
#   powershell -ExecutionPolicy Bypass -File assemble.ps1
$root = $PSScriptRoot
$template = [IO.File]::ReadAllText("$root\whole_code\2026_plain_template.html")
$order = @(Get-Content "$root\blocks.order.txt" | ForEach-Object { $_.Trim() } | Where-Object { $_ -and -not $_.StartsWith('#') })
$rank = @{}
for ($i = 0; $i -lt $order.Count; $i++) { $rank[$order[$i]] = $i }

$files = Get-ChildItem "$root\blocks" -Recurse -Filter *.html |
   Sort-Object -Property @{ Expression = { if ($rank.ContainsKey($_.BaseName)) { $rank[$_.BaseName] } else { [int]::MaxValue } } }, BaseName

$content = @()
$footer = @()
foreach ($f in $files) {
   $text = [IO.File]::ReadAllText($f.FullName).TrimEnd()
   if ($f.Directory.Name -eq 'footer') { $footer += $text } else { $content += $text }
}

$out = "<!-- GENERATED by assemble.ps1 from blocks/ - do not edit by hand -->`r`n" + $template.Replace('<!-- slot: content -->', ($content -join "`r`n")).Replace('<!-- slot: footer -->', ($footer -join "`r`n"))
[IO.File]::WriteAllText("$root\whole_code\2026_plain_email_all_blocks.html", $out, (New-Object Text.UTF8Encoding $false))
Write-Host "Built whole_code/2026_plain_email_all_blocks.html from $($files.Count) blocks"
